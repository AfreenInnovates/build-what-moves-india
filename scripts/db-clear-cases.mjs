import 'dotenv/config';
import pg from 'pg';
const c = new pg.Client({ connectionString: process.env.DATABASE_URL });
await c.connect();
await c.query('delete from events');
await c.query('delete from gate_states');
await c.query('delete from cases');
await c.query(`delete from service_history where member_id in (select id from members where scenario='self')`);
const { rowCount } = await c.query(`delete from members where scenario='self'`);
console.log(`cleared all cases; removed ${rowCount} self-built members`);
await c.end();
